export interface LogEntry {
  id: string;
  time: string;
  message: string;
  operation: "ENQUEUE" | "DEQUEUE" | "CANCEL" | "LOOKUP" | "PRICE" | "SYSTEM";
  complexity: string;
}

export interface Pricing {
  baseFare: number;
  ratePerUnit: number;
}

export interface Stats {
  matched: number;
  cancelled: number;
}

export interface CancelStep {
  title: string;
  detail: string;
}

export interface RiderProfile {
  name: string;
  phone: string;
  email: string;
  home: Point;
  work: Point;
  preferredVehicle: VehicleType;
}

export interface HistoryEntry {
  rideId: string;
  riderName: string;
  vehicleType: VehicleType;
  driverId: string;
  driverName: string;
  fare: number;
  distance: number;
  at: number;
  outcome: "Matched" | "Cancelled";
}

const STORAGE_KEY = "rideshare-dispatch-state-v2";

function nowTime() {
  return new Date().toLocaleTimeString("en-GB", { hour12: false });
}

let idCounter = 0;
function uid() {
  idCounter += 1;
  return `${Date.now().toString(36)}-${idCounter}`;
}

